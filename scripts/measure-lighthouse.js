// Runs Lighthouse mobile performance N times against a URL (production by
// default), takes the median of each metric across runs, and appends the
// result to reports/lighthouse/history.json + regenerates
// reports/lighthouse/TREND.md.
//
// Why this exists: local Lighthouse readings during the 2026-08-06 redesign
// session were unreliable (0.116 / 0.2446 / 0.25-0.54 CLS observed on
// IDENTICAL code across different runs) -- an interactive dev machine with
// this session's own browser instance, IDE, etc. competing for CPU depresses
// Lighthouse's simulated-throttling numbers in a way that varies run to run.
// A GitHub Actions runner is a clean, single-purpose, consistently-sized
// environment -- not perfectly quiet (shared cloud hardware), but far more
// reproducible than a dev machine mid-session, which is why this measures
// from CI on a schedule rather than trusting any one local run.
//
// Usage: node scripts/measure-lighthouse.js [url]
// Requires: scraper/node_modules/lighthouse (npm ci in scraper/ first).

const { execSync } = require("node:child_process");
const fs   = require("node:fs");
const os   = require("node:os");
const path = require("node:path");

const URL_ARG   = process.argv[2] || "https://gaurav-gandhi-2411.github.io/gold-rate-tracker/";
const RUNS      = 5;
// Invoked via `npx --no-install lighthouse` with cwd=scraper/ (not a direct
// path to node_modules/.bin/lighthouse or node_modules/lighthouse/cli/bin.js)
// -- both of those need an OS-specific shim (.cmd on Windows) or hung with no
// output when invoked directly during local testing on this machine. npx
// resolves the correct local shim for the current OS and is already the
// proven-working invocation (same as this session's earlier manual Lighthouse
// runs). `--no-install` guarantees it never silently falls back to
// downloading a different version from the registry if the local one is
// somehow missing -- fails loudly instead.
const SCRAPER_DIR   = path.join(__dirname, "..", "scraper");
const HISTORY_PATH  = path.join(__dirname, "..", "reports", "lighthouse", "history.json");
const TREND_PATH    = path.join(__dirname, "..", "reports", "lighthouse", "TREND.md");
const MAX_TREND_ROWS = 20;

function median(nums) {
  const sorted = [...nums].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? (sorted[mid - 1] + sorted[mid]) / 2 : sorted[mid];
}

function runOnce(url, outPath) {
  const cmd = [
    "npx --no-install lighthouse",
    JSON.stringify(url),
    "--output=json",
    `--output-path=${JSON.stringify(outPath)}`,
    "--only-categories=performance",
    "--preset=perf",
    "--form-factor=mobile",
    "--screenEmulation.mobile",
    '--chrome-flags="--headless=new --no-sandbox"',
    "--quiet",
  ].join(" ");
  try {
    execSync(cmd, { cwd: SCRAPER_DIR, stdio: ["ignore", "ignore", "inherit"] });
  } catch (err) {
    // chrome-launcher's post-run temp-profile cleanup has a known Windows-only
    // race (EPERM deleting its own temp dir) that crashes the CLI with a
    // nonzero exit AFTER the actual report has already been written to
    // outPath -- confirmed empirically (the report parses fine despite the
    // process "failing"). Doesn't reproduce on Linux, which is what the CI
    // runner actually uses, but tolerating it here keeps local runs on
    // Windows from being spuriously flaky. A genuine measurement failure
    // (bad URL, site unreachable) never writes outPath at all, so the
    // readFileSync below still throws and surfaces the real error in that case.
    if (!fs.existsSync(outPath)) throw err;
  }
  const report = JSON.parse(fs.readFileSync(outPath, "utf8"));
  return {
    perf: report.categories.performance.score,
    cls:  report.audits["cumulative-layout-shift"].numericValue,
    lcp:  report.audits["largest-contentful-paint"].numericValue,
    tbt:  report.audits["total-blocking-time"].numericValue,
  };
}

function loadHistory() {
  if (!fs.existsSync(HISTORY_PATH)) return [];
  return JSON.parse(fs.readFileSync(HISTORY_PATH, "utf8"));
}

function writeTrend(history) {
  const rows = history.slice(-MAX_TREND_ROWS).reverse();
  const lines = [
    "# Lighthouse mobile performance trend",
    "",
    "Auto-generated by `.github/workflows/lighthouse.yml` -- do not hand-edit,",
    "changes are overwritten on the next scheduled run. Source of truth is",
    "`reports/lighthouse/history.json` (append-only, full run-level detail).",
    "",
    "Each row is the median of 5 Lighthouse mobile runs against production,",
    "from a GitHub Actions runner (see `scripts/measure-lighthouse.js` for why",
    "CI, not a local dev machine, is the authoritative source here).",
    "",
    "| Date (UTC) | Commit | Perf (median) | CLS (median) | LCP ms (median) | TBT ms (median) |",
    "|---|---|---|---|---|---|",
    ...rows.map((r) => {
      const date = r.timestamp.slice(0, 10);
      const sha  = r.commit_sha ? r.commit_sha.slice(0, 7) : "-";
      return `| ${date} | \`${sha}\` | ${r.perf_median.toFixed(2)} | ${r.cls_median.toFixed(4)} | ${Math.round(r.lcp_median_ms)} | ${Math.round(r.tbt_median_ms)} |`;
    }),
    "",
  ];
  fs.writeFileSync(TREND_PATH, lines.join("\n"));
}

function main() {
  const lighthousePkg = path.join(SCRAPER_DIR, "node_modules", "lighthouse");
  if (!fs.existsSync(lighthousePkg)) {
    console.error(`lighthouse not found under ${lighthousePkg} -- run "npm ci" in scraper/ first.`);
    process.exit(1);
  }

  console.log(`Measuring ${URL_ARG} -- ${RUNS} runs, mobile, performance-only.`);
  const results = [];
  for (let i = 1; i <= RUNS; i++) {
    const tmpPath = path.join(os.tmpdir(), `lh-run-${i}-${Date.now()}.json`);
    console.log(`  run ${i}/${RUNS}...`);
    const r = runOnce(URL_ARG, tmpPath);
    results.push(r);
    fs.rmSync(tmpPath, { force: true });
    console.log(`    perf=${r.perf.toFixed(2)} cls=${r.cls.toFixed(4)} lcp=${Math.round(r.lcp)}ms tbt=${Math.round(r.tbt)}ms`);
  }

  const entry = {
    timestamp: new Date().toISOString(),
    commit_sha: process.env.GITHUB_SHA || null,
    url: URL_ARG,
    device: "mobile",
    runs: results,
    perf_median: median(results.map((r) => r.perf)),
    cls_median: median(results.map((r) => r.cls)),
    lcp_median_ms: median(results.map((r) => r.lcp)),
    tbt_median_ms: median(results.map((r) => r.tbt)),
  };

  console.log("\nMedians:");
  console.log(`  perf: ${entry.perf_median.toFixed(3)}`);
  console.log(`  CLS:  ${entry.cls_median.toFixed(4)}`);
  console.log(`  LCP:  ${Math.round(entry.lcp_median_ms)}ms`);
  console.log(`  TBT:  ${Math.round(entry.tbt_median_ms)}ms`);

  const history = loadHistory();
  history.push(entry);
  fs.mkdirSync(path.dirname(HISTORY_PATH), { recursive: true });
  fs.writeFileSync(HISTORY_PATH, JSON.stringify(history, null, 2) + "\n");
  writeTrend(history);

  console.log(`\nWrote ${HISTORY_PATH} (${history.length} entries) and ${TREND_PATH}.`);
}

main();
