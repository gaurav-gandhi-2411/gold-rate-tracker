"""The RUNBOOK's lock command must be the one in the lock's own header. Until 2026-10-29 the RUNBOOK
added `--extra-index-url https://download.pytorch.org/whl/cpu` and dropped `--python-platform`, so
following it turned `torch==2.13.0` into `torch==2.13.0+cpu`; lock PRs had to ignore the RUNBOOK and
copy the header instead."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _header_command() -> list[str]:
    lines = (ROOT / "ml/requirements-inference.lock").read_text(encoding="utf-8").splitlines()
    assert lines[0].startswith("# This file was autogenerated by uv via the following command:")
    return lines[1].lstrip("#").split()


def _runbook_command() -> list[str]:
    text = (ROOT / "docs/RUNBOOK.md").read_text(encoding="utf-8")
    section = text.split("## Regenerating the inference dependency lockfile", 1)[1]
    block = re.search(r"```bash\n(.*?)```", section.replace("\r\n", "\n"), flags=re.DOTALL)
    assert block is not None, "the lockfile section has no bash block"
    joined = block.group(1).replace("\\\n", " ")
    commands = [ln for ln in joined.splitlines() if ln.strip().startswith("uv pip compile")]
    assert len(commands) == 1, commands
    return commands[0].split()


def test_runbook_lock_command_is_the_lock_header_command():
    assert _runbook_command() == _header_command()


def test_runbook_lock_command_does_not_swap_torch_to_the_cpu_index():
    assert "--extra-index-url" not in _runbook_command()
